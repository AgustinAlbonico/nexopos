async function runSeed() {
    try {
        console.log('🚀 Conectando a la base de datos para cargar los 20 proveedores de prueba...');
        await dataSource.initialize();
        console.log('✅ Conexión establecida.');

        const supplierRepo = dataSource.getRepository(Supplier);

        let createdCount = 0;
        let updatedCount = 0;

        for (const data of suppliersData) {
            const existing = await supplierRepo.findOne({
                where: { documentNumber: data.documentNumber },
            });

            if (existing) {
                Object.assign(existing, data);
                await supplierRepo.save(existing);
                updatedCount++;
                console.log(`🔄 Actualizado: ${data.name} [Clasificación: "${data.classification}"]`);
            } else {
                const newSupplier = supplierRepo.create(data);
                await supplierRepo.save(newSupplier);
                createdCount++;
                console.log(`✨ Creado: ${data.name} [Clasificación: "${data.classification}"]`);
            }
        }

        console.log('\n=============================================');
        console.log(`🎉 Proceso finalizado con éxito:`);
        console.log(`   - Creados: ${createdCount}`);
        console.log(`   - Actualizados: ${updatedCount}`);
        console.log(`   - Total clasificaciones distintas cargadas: ${suppliersData.length}`);
        console.log('=============================================');
    } catch (error) {
        console.error('❌ Error al ejecutar el seed de proveedores:', error);
        process.exit(1);
    } finally {
        if (dataSource.isInitialized) {
            await dataSource.destroy();
        }
    }
}

runSeed();
